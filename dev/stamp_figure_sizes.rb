# frozen_string_literal: true

# Records the display size of every gallery figure in docs/_data/figure_sizes.yml.
#
# The gallery used to hand each PNG to the browser with no size, so a figure was
# drawn at its natural size when it fitted the column and shrunk when it did
# not. Since a tree's pixel size follows its content, a short tree appeared at
# 100% next to a wide one at 30%, and the same 16px label looked twice as large
# in one figure as in the next.
#
# A single scale factor for every figure is no better: it either leaves the
# small figures too large or shrinks them past the point of being readable,
# while the wide ones are governed by the column regardless. So the factor
# varies with the figure's own width, easing from full size for a tiny tree
# down to the column limit for a wide one:
#
#   displayed width = min(column, k * width ** EXPONENT)
#
# An exponent below 1 makes the displayed width grow more slowly than the
# figure itself, which is exactly the compression the eye is asking for; k is
# set so that a 280px figure lands at about 90%. The result runs roughly 100%
# for a tiny tree, 90% at 280px, 77% at 520px, 65% at 690px, and meets the
# column cap from there on — a gradient rather than the step a fixed factor
# produces. Nothing is ever scaled up.
#
# Jekyll cannot measure images on GitHub Pages, hence this file. Run from the
# repository root, after generating the examples:
#
#   ruby dev/stamp_figure_sizes.rb

require "yaml"
require "fileutils"

IMG_DIR = File.expand_path("../docs/assets/img", __dir__)
DATA_FILE = File.expand_path("../docs/_data/figure_sizes.yml", __dir__)

# How much room the figure gets, measured on the built page. A figure narrow
# enough to sit beside the bracket notation keeps the even two-column split; a
# wider one takes two thirds of the row, and one wider still gets a row of its
# own below the notation. Each tier is a class on the grid in
# docs/assets/css/style.scss, and the stylesheet caps anything that still
# overflows, so approximate numbers here cost nothing.
LAYOUTS = [
  { max_width: 600,   column: 448.0, css_class: "" },
  { max_width: 1400,  column: 604.0, css_class: "grid-wide" },
  # No cap on the widest tier. Shrinking a 3000px tree to fit the page leaves a
  # figure that is neither readable nor informative, so it keeps the scale the
  # easing gives it — around 50%, falling to 30% for the extreme cases — and
  # the page scrolls it sideways instead. A tree reads left to right anyway.
  { max_width: nil,   column: nil,   css_class: "grid-stack" }
].freeze

# Width of the widest row. A figure drawn wider than this scrolls in place.
CONTAINER_WIDTH = 940.0

EXPONENT = 0.75
# Chosen so that a 280px-wide figure is shown at ~90% of its rendered size.
COEFFICIENT = 3.68

# Width and height out of the PNG's IHDR chunk, which always starts at byte 16.
def png_size(path)
  header = File.binread(path, 24)
  raise "#{path}: not a PNG" unless header && header[1, 3] == "PNG"

  header[16, 8].unpack("N2")
end

def layout_for(width)
  LAYOUTS.find { |l| l[:max_width].nil? || width <= l[:max_width] }
end

def display_scale(width, column)
  eased = COEFFICIENT * (width**EXPONENT)
  eased = [eased, column].min if column
  [eased / width, 1.0].min
end

sizes = Dir.glob(File.join(IMG_DIR, "*.png")).sort.each_with_object({}) do |path, acc|
  name = File.basename(path, ".png")
  width, height = png_size(path)
  layout = layout_for(width)
  scale = display_scale(width, layout[:column])
  display_width = (width * scale).round
  acc[name] = {
    "width" => display_width,
    "height" => (height * scale).round,
    "layout" => layout[:css_class],
    "scroll" => display_width > CONTAINER_WIDTH
  }
end

abort "no figures found in #{IMG_DIR}" if sizes.empty?

FileUtils.mkdir_p(File.dirname(DATA_FILE))
File.write(DATA_FILE, <<~HEADER + sizes.to_yaml.sub(/\A---\n/, ""))
  # Generated by dev/stamp_figure_sizes.rb — do not edit by hand.
  # Display size of each gallery figure, eased down by a factor that grows with
  # the figure's width so the apparent scale stays comparable from one figure to
  # the next, plus the grid class that decides how much of the row it gets.
HEADER

puts "wrote #{sizes.size} figure sizes to #{DATA_FILE.sub("#{Dir.pwd}/", "")}"
